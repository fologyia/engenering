def _normalizar(nome: str) -> str:
    sem_marcas = re.sub(r"\s*\(H\)|\*", "", str(nome)).strip()
    return re.sub(r"\s+", " ", sem_marcas)


def k_tabelado_mm(nome: str, tf_mm: float) -> float | None:
    """``k = t_f + (h − d')/2`` do catálogo; ``None`` quando o perfil não está na tabela."""
    dados = H_E_D_LINHA_MM.get(_normalizar(nome))
    if dados is None:
        return None
    h, d_linha = dados
    return float(tf_mm) + (h - d_linha) / 2.0
